-- Supabase schema example for ScentVault AI

create table if not exists perfumes (
  id bigint primary key,
  brand text not null,
  name text not null,
  concentration text,
  size_ml integer,
  remaining_ml integer,
  rating numeric default 0,
  seasons text[] default '{}',
  image text,
  notes jsonb default '{}'
);

create table if not exists logs (
  id bigint primary key,
  date text,
  perfume_name text not null,
  sprays integer default 1,
  occasion text,
  created_at timestamptz default now()
);

create table if not exists wishlist (
  id bigint generated by default as identity primary key,
  name text,
  brand text,
  note text,
  created_at timestamptz default now()
);

create table if not exists public.perfume_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  original_perfume_id bigint,
  brand text not null,
  name text not null,
  concentration text,
  size_ml integer,
  purchase_date date,
  finished_date date not null default current_date,
  rating numeric default 0,
  seasons text[] default '{}',
  image text,
  notes jsonb default '{}',
  archived_at timestamptz not null default now()
);

create index if not exists perfumes_brand_idx on perfumes (brand);
create index if not exists logs_created_at_idx on logs (created_at desc);
create index if not exists perfume_history_user_finished_idx on public.perfume_history (user_id, finished_date desc);

alter table public.perfumes
  add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.perfumes
  add column if not exists purchase_date date;
alter table public.logs
