alter table public.wishlist
  add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.perfumes enable row level security;
alter table public.logs enable row level security;
alter table public.wishlist enable row level security;
alter table public.perfume_history enable row level security;

revoke all on table public.perfumes, public.logs, public.wishlist from anon, public;
grant select, insert, update, delete on table public.perfumes, public.logs, public.wishlist to authenticated;
revoke all on table public.perfume_history from anon, public;
grant select, insert, delete on table public.perfume_history to authenticated;
revoke all on sequence public.wishlist_id_seq from anon, public;
grant usage, select on sequence public.wishlist_id_seq to authenticated;
revoke all on sequence public.perfume_history_id_seq from anon, public;
grant usage, select on sequence public.perfume_history_id_seq to authenticated;

